# -*- coding: utf-8 -*-
"""
n8n_adapter.py
--------------
Orchestration adapter for n8n workflow integration.
Provides structured, idempotent payloads for n8n nodes:
- Research run triggering
- Experiment queue polling
- Candidate topic selection
- Discord review notification formatting
- Snapshot check dispatching
- Outcome evaluation polling

INVARIANT: n8n orchestrates workflows but NEVER bypasses the human Discord approval gate.
"""

import json
from typing import Dict, Any, List, Optional
from growth.db.models import GrowthRepository
from growth.experiments.experiment_queue import ExperimentQueue
from growth.experiments.lineage_tracker import ExperimentLineageTracker
from growth.planner.content_planner import ContentPlanner


class N8nExperimentAdapter:
    """
    Adapter interfacing between n8n workflow automations and the Growth Experiment Engine.
    """
    def __init__(self, repo: Optional[GrowthRepository] = None):
        self.repo = repo or GrowthRepository()
        self.queue = ExperimentQueue(self.repo)
        self.tracker = ExperimentLineageTracker(self.repo)
        self.planner = ContentPlanner(self.repo)

    def get_orchestration_status(self, channel_id: str) -> Dict[str, Any]:
        """
        Returns a complete state snapshot for n8n orchestration decision trees.
        """
        ready_exps = self.queue.get_ready_experiments(channel_id)
        all_queued = self.queue.get_all_queued_experiments(channel_id)
        published_vids = self.repo.list_videos_by_channel(channel_id)

        return {
            "channel_id": channel_id,
            "ready_experiments_count": len(ready_exps),
            "ready_experiments": ready_exps,
            "total_active_experiments": len(all_queued),
            "published_videos_count": len(published_vids),
            "human_approval_required": True,
            "pipeline_isolation_locked": True
        }

    def format_discord_review_payload(
        self,
        job_id: str,
        video_plan: Dict[str, Any],
        video_metadata: Dict[str, Any]
    ) -> Dict[str, Any]:
        """
        Formats a structured, human-readable Discord review notification payload
        containing full experiment metadata and audit lineage.
        """
        exp_id = video_plan.get("experiment_id")
        arm_id = video_plan.get("arm_id")
        var_type = video_plan.get("experiment_variant", "CONTROL")
        var_under_test = video_plan.get("variable_under_test")

        fields = [
            {"name": "Topic", "value": video_plan.get("topic", "Unknown"), "inline": False},
            {"name": "Channel", "value": video_plan.get("channel_id", "channel_a").upper(), "inline": True},
            {"name": "Strategy Version", "value": video_plan.get("strategy_version", "v1.0"), "inline": True},
            {"name": "Job ID", "value": f"`{job_id}`", "inline": True}
        ]

        if exp_id:
            fields.append({"name": "🧪 Experiment Under Test", "value": f"`{exp_id}`", "inline": False})
            fields.append({"name": "Arm / Variant", "value": f"**{var_type}** (`{arm_id}`)", "inline": True})
            fields.append({"name": "Variable Isolated", "value": f"`{var_under_test}`", "inline": True})
            fields.append({"name": "Allocation Tier", "value": video_plan.get("allocation_tier", "adjacent"), "inline": True})

        return {
            "job_id": job_id,
            "requires_human_approval": True,
            "embed": {
                "title": f"🎬 Production Ready for Review: {video_plan.get('topic')}",
                "description": f"Video generated by `{video_plan.get('pipeline_id')}` and ready for Discord operator review.",
                "color": 0x3498db if not exp_id else 0x9b59b6,
                "fields": fields
            }
        }
